DEFAULT_TIMEZONE = "Asia/Shanghai"

_SUFFIXES = (
    "特别行政区", "自治区", "自治州", "地区", "新区", "经济特区",
    "省", "市", "县", "区", "镇",
)


def _normalize(text: str) -> str:
    value = text.strip().replace(" ", "")
    for suffix in _SUFFIXES:
        if value.endswith(suffix) and len(value) > len(suffix):
            value = value[: -len(suffix)]
    return value


def lookup_city(place: str) -> tuple[str, float, str] | None:
    """按城市名模糊查经度与时区，查不到返回 None。

    支持「四川成都」「成都市」「成都」等写法；优先最长匹配。
    """
    if not place:
        return None
    text = _normalize(place)
    if text in CITY_LONGITUDE:
        return text, CITY_LONGITUDE[text], CITY_TIMEZONE.get(text, DEFAULT_TIMEZONE)
    # 输入可能是「四川成都」「四川省成都市」等，取包含的已知城市名，最长优先
    matches = [name for name in CITY_LONGITUDE if name in text]
    if matches:
        name = max(matches, key=len)
        return name, CITY_LONGITUDE[name], CITY_TIMEZONE.get(name, DEFAULT_TIMEZONE)
    return None
